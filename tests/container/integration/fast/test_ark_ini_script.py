"""ark-ini.py and the INI files' git history across a boot, a server run and set, on the lite image."""

from __future__ import annotations

import json

import pytest
from helpers.compose_client import compose_exec, compose_run, compose_stop
from python_on_whales import DockerClient
from python_on_whales.exceptions import DockerException

pytestmark = [pytest.mark.container, pytest.mark.lite]

_PY = "/usr/bin/python3.14"
_SCRIPT = "/home/ark-user/scripts/runtime/ark-ini.py"
_CONFIG = "/home/ark-user/ark-server/ShooterGame/Saved/Config/WindowsServer"
_SET = [_PY, _SCRIPT, "set", "--file", "gameusersettings", "--section", "ServerSettings", "--key", "MaxPlayers"]


def _history(compose_client: DockerClient, instance: str, *, running: bool) -> list[str]:
    """The INI history, newest first, as 'author: subject'."""
    cmd = ["git", "-C", _CONFIG, "log", "--format=%an: %s"]
    if running:
        return (compose_exec(compose_client, instance, cmd) or "").splitlines()
    return str(compose_run(compose_client, instance, cmd[1:], remove=True, entrypoint="git")).splitlines()


def test_ini_history_follows_boot_server_and_set(
    test_env: dict[str, str],
    compose_client: DockerClient,
    started_container_instance: dict[str, str],
) -> None:
    """The INI history records the default, the env settings, the server's shutdown write and set ini.

    Scenario:
        A fresh lite instance (default INI installed; the fake server rewrites it on DoExit).
        ark-ini.py get and set run while up, then the service stops, then set runs in a one-off
        container.

    Expected:
        - While running: the history is the image default (ARK) then the env settings; get reads
          MaxPlayers as written by ARK; set is refused.
        - After the stop: the server's write (FakeArkShutdowns=1) is committed as ARK's.
        - Stopped: set changes MaxPlayers 70 -> 20 and is committed as ark-cli's.
    """
    instance = started_container_instance["instance"]
    assert _history(compose_client, instance, running=True) == [
        "instance env: RCON and password settings from the environment",
        "ARK server: image default installed (generated by ARK at image build)",
    ]

    get = [_PY, _SCRIPT, "get", "--file", "gameusersettings", "--section", "ServerSettings", "--key", "MaxPlayers"]
    line = json.loads(compose_exec(compose_client, instance, get) or "")["lines"][0]
    assert line["value"] == "70"
    assert line["origin"].startswith("written by ARK 20"), line

    with pytest.raises(DockerException) as refused:
        compose_exec(compose_client, instance, [*_SET, "--value", "20"])
    assert "server is running" in str(refused.value.stderr)

    compose_stop(compose_client, instance, timeout=120)
    history = _history(compose_client, instance, running=False)
    assert history[0] == "ARK server: written by the server during its run (exit code 0)", history

    reply = json.loads(
        str(compose_run(compose_client, instance, [_SCRIPT, *_SET[2:], "--value", "20"], remove=True, entrypoint=_PY))
    )
    assert (reply["old"], reply["changed"]) == (["70"], True)
    assert _history(compose_client, instance, running=False)[0] == "ark-cli set ini: [ServerSettings] MaxPlayers=20"
