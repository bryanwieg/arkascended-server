"""The INI history against the real ARK server (what the lite image's fake assumes)."""

from __future__ import annotations

from typing import TYPE_CHECKING

import pytest
from helpers.compose_client import compose_exec, compose_run, compose_stop

if TYPE_CHECKING:
    from python_on_whales import DockerClient

pytestmark = [pytest.mark.container, pytest.mark.real_server]

_CONFIG = "/home/ark-user/ark-server/ShooterGame/Saved/Config/WindowsServer"


def test_real_server_shutdown_write_is_committed_as_ark(
    compose_client: DockerClient,
    slow_test_protection,
    started_container_instance: dict[str, str],
) -> None:
    """ARK's own shutdown rewrite of GameUserSettings.ini lands in the INI history as ARK's.

    Scenario:
        A fresh instance starts (the entrypoint commits the image default as ARK's, then the RCON
        settings as the env's). The service is stopped gracefully, so ARK rewrites the file.

    Expected:
        - While running, the history is the default then the env settings.
        - After the stop, the newest commit is the server's write and nothing is left
          uncommitted: ARK changed the file during the run and the start script committed it.
    """
    instance = started_container_instance["instance"]
    log = ["git", "-C", _CONFIG, "log", "--format=%an: %s"]

    history = (compose_exec(compose_client, instance, log) or "").splitlines()
    assert history == [
        "instance env: RCON and password settings from the environment",
        "ARK server: image default installed (generated by ARK at image build)",
    ]

    compose_stop(compose_client, instance, timeout=900)
    history = str(compose_run(compose_client, instance, log[1:], remove=True, entrypoint="git")).splitlines()
    status = str(
        compose_run(compose_client, instance, ["-C", _CONFIG, "status", "--porcelain"], remove=True, entrypoint="git")
    )
    assert history[0] == "ARK server: written by the server during its run (exit code 0)", history
    assert status.strip() == ""
